CELL_AVERAGE = """\
/// The average of `f` over the axis-aligned box `[lo, hi]` by the
/// tensor-product 4-point Gauss-Legendre rule: 4 points per direction in
/// 3-D, 4 points in x and y with one point at mid-z in 2-D. The rule is
/// exact to degree 7 per direction, so on a smooth field its error is
/// O(h^8), far below the O(h^2) discretisation error it feeds - and it is
/// a box rule only: hex/box cells, not general polyhedra (those would
/// need face-pyramid decomposition, not implemented).
///
/// Panics if `dim` is neither 2 nor 3, or if `hi[i] <= lo[i]` in a used
/// direction.
pub fn cell_average(f: impl Fn([f64; 3]) -> f64, lo: [f64; 3], hi: [f64; 3], dim: usize) -> f64 {
    assert!(dim == 2 || dim == 3, "cell_average: dim must be 2 or 3, got {dim}");
    let mut volume = 1.0;
    for i in 0..dim {
        assert!(hi[i] > lo[i], "cell_average: hi[{i}] must be greater than lo[{i}]");
        volume *= hi[i] - lo[i];
    }
    let mid_x = 0.5 * (lo[0] + hi[0]);
    let mid_y = 0.5 * (lo[1] + hi[1]);
    let mid_z = 0.5 * (lo[2] + hi[2]);
    let half_x = 0.5 * (hi[0] - lo[0]);
    let half_y = 0.5 * (hi[1] - lo[1]);
    let half_z = 0.5 * (hi[2] - lo[2]);
    let mut integral = 0.0;
    for ix in 0..GAUSS_POINTS {
        let px = mid_x + half_x * GAUSS_NODES[ix];
        let wx = half_x * GAUSS_WEIGHTS[ix];
        for iy in 0..GAUSS_POINTS {
            let py = mid_y + half_y * GAUSS_NODES[iy];
            let wxy = wx * half_y * GAUSS_WEIGHTS[iy];
            if dim == 3 {
                for iz in 0..GAUSS_POINTS {
                    let pz = mid_z + half_z * GAUSS_NODES[iz];
                    integral += wxy * half_z * GAUSS_WEIGHTS[iz] * f([px, py, pz]);
                }
            } else {
                integral += wxy * f([px, py, mid_z]);
            }
        }
    }
    integral / volume
}

/// One manufactured case: the exact field, its derivatives, and the
/// default velocity and diffusivity of its governing equation.
#[derive(Debug, Clone, Copy)]
pub struct Case {
    /// `"VER-01-2D"`, `"VER-01-3D"`, `"VER-02-2D"`, `"VER-02-3D"`.
    pub id: &'static str,
    /// 2 or 3: the field is z-independent when this is 2.
    pub dim: usize,
    /// VER-01 ignores `t`; VER-02 carries `(1 + EPS * sin(OMEGA * t))`.
    pub steady: bool,
    /// The default constant velocity of the case's equation.
    pub u0: [f64; 3],
    /// The default diffusivity of the case's equation.
    pub gamma0: f64,
    pub phi: fn([f64; 3], f64) -> f64,
    pub grad_phi: fn([f64; 3], f64) -> [f64; 3],
    pub dphi_dt: fn([f64; 3], f64) -> f64,
    pub lap_phi: fn([f64; 3], f64) -> f64,
}

impl Case {
    /// The exact source `dphi/dt + u . grad(phi) - gamma * lap(phi)` that
    /// keeps `phi` a solution of the governing equation: what the verified
    /// code is fed, as a point value.
    pub fn source(&self, x: [f64; 3], t: f64, u: [f64; 3], gamma: f64) -> f64 {
        let g = (self.grad_phi)(x, t);
        (self.dphi_dt)(x, t)
            + u[0] * g[0]
            + u[1] * g[1]
            + u[2] * g[2]
            - gamma * (self.lap_phi)(x, t)
    }

    /// The cell average of [`Case::source`] over the box `lo..hi` by the
    /// same rule as [`cell_average`] - the form the sources are injected
    /// in, because a cell-centre point value would contaminate the second
    /// and higher orders it is meant to verify.
    pub fn source_cell_average(
        &self,
        lo: [f64; 3],
        hi: [f64; 3],
        t: f64,
        u: [f64; 3],
        gamma: f64,
    ) -> f64 {
        cell_average(|p| self.source(p, t, u, gamma), lo, hi, self.dim)
    }

    /// The cell average of `phi` itself over the box `lo..hi`.
    pub fn phi_cell_average(&self, lo: [f64; 3], hi: [f64; 3], t: f64) -> f64 {
        cell_average(|p| (self.phi)(p, t), lo, hi, self.dim)
    }
}"""


def param_args(printed):
    """Typed `x: [f64; 3], t: f64` args, `_`-prefixed when unused."""
    x = "x" if re.search(r"\bx\b", printed) else "_x"
    t = "t" if re.search(r"\bt\b", printed) else "_t"
    return "%s: [f64; 3], %s: f64" % (x, t)


def case_module(cid, mod, dim, steady, cases):
    """One `pub mod` of closed forms: phi, grad_phi, dphi_dt, lap_phi.

    Every expression prints through expand(): the Rust printer flattens an
    Add factor inside a Mul WITHOUT keeping its parentheses, so a factored
    unsteady derivative would print as the wrong algebra. Expanded, every
    product is flat and the printed form is the algebra.
    """
    phi_s = cases.PHI_2D if dim == 2 else cases.PHI_3D
    phi = phi_s if steady else expand(phi_s * (1 + cases.EPS * sin(cases.OMEGA * cases.T)))
    comps = [expand(diff(phi, cases.X)), expand(diff(phi, cases.Y))]
    comps.append(expand(diff(phi, cases.Z)) if dim == 3 else None)
    lap = expand(diff(phi, cases.X, 2) + diff(phi, cases.Y, 2)
                 + (diff(phi, cases.Z, 2) if dim == 3 else 0))
    dt = None if steady else expand(diff(phi, cases.T))

    def ex(e):
        return to_array_args(rust_expr(e)) if e is not None else "0.0"

    pt_args = param_args(rust_expr(phi))
    shape = ("the steady Roy-form trigonometric field, independent of z"
             if steady and dim == 2 else
             "the steady Roy-form trigonometric field with the z terms"
             if steady else
             "the Roy-form field times (1 + EPS * sin(OMEGA * t)), independent of z"
             if dim == 2 else
             "the Roy-form field times (1 + EPS * sin(OMEGA * t)), with the z terms")
    grad_body = "[\n        " + ",\n        ".join(
        wrap_expr(ex(c), 84, "\n            ") for c in comps) + ",\n    ]"
    fns = [
        ("phi", "f64", wrap_expr(ex(phi))),
        ("grad_phi", "[f64; 3]", grad_body),
        ("dphi_dt", "f64", "0.0" if dt is None else wrap_expr(ex(dt))),
        ("lap_phi", "f64", wrap_expr(ex(lap))),
    ]
    parts = []
    for name, ret, body in fns:
        args = "_x: [f64; 3], _t: f64" if name == "dphi_dt" and steady else pt_args
        parts.append("pub fn %s(%s) -> %s {\n    %s\n}" % (name, args, ret, body))
    body = "\n\n".join(parts)
    indented = "\n".join(("    " + ln) if ln else ln for ln in body.split("\n"))
    return "/// %s: %s.\npub mod %s {\n    use super::*;\n\n%s\n}" % (
        cid, shape, mod, indented)


def case_const(mod, cid, dim, steady, u0):
    uname = mod.upper()
    lines = ["/// %s (`%s`)." % (uname, cid)]
    lines.append("pub const %s: Case = Case {" % uname)
    lines += [
        '    id: "%s",' % cid,
        "    dim: %d," % dim,
        "    steady: %s," % ("true" if steady else "false"),
        "    u0: [%s]," % ", ".join(repr(v) for v in u0),
        "    gamma0: GAMMA0,",
        "    phi: %s::phi," % mod,
        "    grad_phi: %s::grad_phi," % mod,
        "    dphi_dt: %s::dphi_dt," % mod,
        "    lap_phi: %s::lap_phi," % mod,
        "};",
    ]
    return "\n".join(lines)


