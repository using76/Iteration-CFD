PDE_TEX = (r"\frac{\partial \phi}{\partial t} + \nabla \cdot "
           r"\left( \mathbf{U} \phi \right) - \nabla \cdot "
           r"\left( \Gamma \nabla \phi \right) = S")
S_DEF_TEX = (r"S = \frac{\partial \phi}{\partial t} + \mathbf{U} \cdot "
             r"\nabla \phi - \Gamma \, \nabla^{2} \phi")
AVG_TEX = (r"\bar{S}_{P} = \frac{1}{\left| V_{P} \right|} \int_{V_{P}} S "
           r"\, dV \approx \frac{1}{\left| V_{P} \right|} "
           r"\sum_{i=1}^{4} \sum_{j=1}^{4} \sum_{k=1}^{4} w_{i} w_{j} w_{k}"
           r" \, S \! \left( x_{i}, y_{j}, z_{k} \right)")


def sym_names(cases):
    return {
        cases.L: "L", cases.PHI0: r"\phi_{0}", cases.PHI_X: r"\phi_{x}",
        cases.PHI_Y: r"\phi_{y}", cases.PHI_Z: r"\phi_{z}",
        cases.PHI_XY: r"\phi_{xy}", cases.PHI_YZ: r"\phi_{yz}",
        cases.A_X: r"a_{x}", cases.A_Y: r"a_{y}", cases.A_Z: r"a_{z}",
        cases.A_XY: r"a_{xy}", cases.A_YZ: r"a_{yz}",
        cases.EPS: r"\varepsilon", cases.OMEGA: r"\omega",
        cases.UX: r"U_{x}", cases.UY: r"U_{y}", cases.UZ: r"U_{z}",
        cases.GAMMA: r"\Gamma",
    }


def source_expr(cases, f, n):
    """S = dphi/dt + U . grad(phi) - Gamma lap(phi), U and Gamma symbolic."""
    usyms = [cases.UX, cases.UY, cases.UZ]
    s = diff(f, cases.T)
    for v, u in zip((cases.X, cases.Y, cases.Z)[:n], usyms):
        s = s + u * diff(f, v)
    lap = sum(diff(f, v, 2) for v in (cases.X, cases.Y, cases.Z)[:n])
    return s - cases.GAMMA * lap


def render_manifest(cases, cid):
    steady = cid == "VER-01"
    m = cases.MANIFESTS[cid]
    tf = 1 if steady else (1 + cases.EPS * sin(cases.OMEGA * cases.T))
    names = sym_names(cases)

    def tex(e):
        return latex(expand(e), symbol_names=names)

    equations = [
        {"env": "equation", "tex": PDE_TEX},
        {"env": "equation", "tex": latex(cases.PHI_2D, symbol_names=names)},
        {"env": "equation", "tex": latex(cases.PHI_3D, symbol_names=names)},
        {"env": "equation", "tex": S_DEF_TEX},
        {"env": "equation", "tex": tex(source_expr(cases, cases.PHI_2D * tf, 2))},
        {"env": "equation", "tex": tex(source_expr(cases, cases.PHI_3D * tf, 3))},
        {"env": "equation", "tex": AVG_TEX},
    ]
    obj = {
        "id": cid,
        "title": m["title"],
        "intro": m["intro"],
        "equations": equations,
        "parameters": cases.MANIFEST_PARAMS[cid],
        "sources": cases.SOURCES,
    }
    return json.dumps(obj, ensure_ascii=False, indent=2) + "\n"


def outputs(cases):
    return {
        "rust/src/vv/mms.rs": render_rust(cases),
        "docs/vv/formulas/VER-01.json": render_manifest(cases, "VER-01"),
        "docs/vv/formulas/VER-02.json": render_manifest(cases, "VER-02"),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate rust/src/vv/mms.rs and the formula manifests.")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; fail if a generated file differs")
    args = ap.parse_args(argv)
    texts = outputs(load_cases())
    if args.check:
        bad = []
        for rel, want in texts.items():
            path = REPO / rel
            have = path.read_bytes() if path.exists() else None
            if have != want.encode("utf-8"):
                bad.append(rel)
        if bad:
            for rel in bad:
                print("mms: out of date or missing: %s" % rel)
            return 1
        print("mms: 3 files up to date")
        return 0
    for rel, text in texts.items():
        path = REPO / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("mms: wrote %s" % rel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
