_PRINTER = RustCodePrinter()


def rust_expr(expr):
    """Print expr as Rust in terms of the named constants, rustfmt-like."""
    s = _PRINTER.doprint(expr)
    s = re.sub(r"\s*\*\s*", " * ", s)
    s = re.sub(r"\s*\+\s*", " + ", s)
    s = re.sub(r"\s*/\s*", " / ", s)
    s = re.sub(r"(?<![eE])([0-9a-zA-Z_\)\]]) ?- ", r"\1 - ", s)
    return s


def to_array_args(s):
    """The coordinates arrive as `x: [f64; 3]`: x, y, z -> x[0], x[1], x[2]."""
    s = re.sub(r"\bx\b", "x[0]", s)
    s = re.sub(r"\by\b", "x[1]", s)
    s = re.sub(r"\bz\b", "x[2]", s)
    return s


def split_top(s, sep):
    """Split on `sep` at bracket depth 0 only."""
    parts, depth, last, i = [], 0, 0, 0
    while i < len(s):
        c = s[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif depth == 0 and s.startswith(sep, i):
            parts.append(s[last:i])
            i += len(sep)
            last = i
            continue
        i += 1
    parts.append(s[last:])
    return parts


def split_terms(s):
    """Split a printed Add at top-level ` + ` / ` - ` boundaries.

    The first piece carries no operator; every later piece starts with its
    sign (`+ ` or `- `).
    """
    parts, depth, last, i = [], 0, 0, 0
    while i < len(s):
        c = s[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif depth == 0 and (s.startswith(" + ", i) or s.startswith(" - ", i)):
            parts.append(s[last:i])
            last = i + 1
            i += 3
            continue
        i += 1
    parts.append(s[last:])
    return parts


def wrap_expr(s, width=92, indent="\n        "):
    """Break a long expression at top-level term boundaries, operator at
    line end, rustfmt-style."""
    if len(s) <= width:
        return s
    terms = split_terms(s)
    lines = [terms[0]]
    for t in terms[1:]:
        op, term = t[0], t[2:]
        if len(lines[-1]) + 3 + len(term) <= width:
            lines[-1] += " %s %s" % (op, term)
        else:
            lines[-1] += " +" if op == "+" else " -"
            lines.append(term)
    return indent.join(lines)


def gauss_rule():
    """The 4-point Gauss-Legendre rule, printed to 17 significant digits."""
    nodes, weights = gauss_legendre(4, n_digits=30)
    fns = ["%.17g" % v for v in nodes]
    fws = ["%.17g" % v for v in weights]
    assert all(float(s) == float(v) for s, v in zip(fns, nodes))
    assert all(float(s) == float(v) for s, v in zip(fws, weights))
    assert abs(sum(float(v) for v in weights) - 2.0) < 1e-12
    return fns, fws


