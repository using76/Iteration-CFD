"""The Iterations promo opening's stagnation field: write, run, export, inline, check.

The v6 promo opening plays a real planar impinging (stagnation) flow solved by
the pinned GPU solver ``ofgpu-lowmach``: flow enters at x = 0 at 1 m/s, hits a
no-slip wall at x = 3.2 m and turns through two open outlets, on a 56 x 48 x 1
graded channel mesh whose cells tighten toward the wall. ``write`` generates the
mesh with the release ``ofgpu-generate-mesh`` (a separate program), retypes the
preset's patches and writes the laminar case; ``run`` sha256-checks the pinned
binary, records the GPU state before and after and streams the 800-iteration
steady SIMPLE solve into ``solve.log``; ``export`` bilinearly samples the
converged field onto the opening's 64 x 54 grid and writes
``tools/promo/video/opening/stagnation_field.json``; ``inline`` writes that JSON
as one line into title.html between the OPENING-FIELD markers; ``check`` judges
the eight gates G1-G8. Case outputs are never written inside the repository.
numpy (BSD-3) and scipy (BSD-3) are imported. No GPL-licensed source was
consulted.
"""

