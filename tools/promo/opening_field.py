NU = 0.01
U_IN = 1.0
T_IN = 293.15
SAMPLE_X0, SAMPLE_DX, SAMPLE_NX = 0.025, 0.05, 64
SAMPLE_Y0, SAMPLE_DY, SAMPLE_NY = -1.325, 0.05, 54
