def _g1_sample(H):
    b = H["bundle"]
    s = sample(b)
    assert s["n"] == 97, s["n"]
    assert s["n_plane"] == 37, s["n_plane"]
    assert s["n_plane_geometries"] == 36, s["n_plane_geometries"]
    assert s["n_other"] == 60, s["n_other"]
    assert s["n_other_pool"] == 765, s["n_other_pool"]
    assert s["n_candidates"] == 802, s["n_candidates"]
    assert s["n_rows_total"] == 805, s["n_rows_total"]
    assert s["n_strata"] == 16, s["n_strata"]
    assert s["quotas"] == {"A/easy": 1, "A/hard": 6, "A/medium": 6, "B/easy": 2,
                           "B/hard": 8, "B/medium": 6, "D/hard": 2, "D/medium": 9,
                           "E/easy": 3, "E/hard": 2, "E/medium": 2, "F/easy": 1,
                           "F/hard": 3, "F/medium": 2, "G/easy": 5, "G/medium": 2}, \
        s["quotas"]
    assert s["sha256"] == \
        "91b21b3df602594cbc51b61d6a933adee94b8210083720e7616f52f001bee20b", \
        s["sha256"]
    ids = ["%s:%d" % (e["geometry_id"], e["attempt"]) for e in s["rows"]]
    assert ids[:3] == ["A-1-003:1", "A-1-006:1", "A-1-007:2"], ids[:3]
    assert ids[-2:] == ["G-1-106:1", "G-1-117:2"], ids[-2:]
    for e in s["rows"]:
        assert e["recorded_content_sha256"] is not None, e
    plane_rows = [e for e in s["rows"] if e["plane"]]
    pg = plane_geometries(b)
    assert len(plane_rows) == 37, len(plane_rows)
    assert all(e["geometry_id"] in pg for e in plane_rows)
    s2 = sample(b)
    assert s2["rows"] == s["rows"]
    b3 = copy.deepcopy(b)
    for ln in b3["records"]:
        rec = ln.get("record") or {}
        if (ln.get("attempt") == 1 and rec.get("rule_id") == "R-PLANE"
                and rec.get("verdict") == "apply" and rec.get("edits")
                and ln["geometry_id"] == "D-1-042"):
            rec["verdict"] = "pass"
            break
    s3 = sample(b3)
    assert s3["n_plane"] == 36, s3["n_plane"]
