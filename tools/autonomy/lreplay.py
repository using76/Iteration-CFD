def selftest():
    H = {"bundle": load_bundle(BUNDLE_DEFAULT)}
    groups = (("sample", _g1_sample), ("rebuild", _g2_rebuild),
              ("seal", _g3_seal), ("verdict", _g4_verdict),
              ("scripted run", _g5_scripted), ("live", _g6_live))
    bad = 0
    for name, fn in groups:
        try:
            text = fn(H)
        except Exception as e:  # noqa: BLE001 - the failure IS the report
            bad += 1
            print("SELFTEST FAIL: %s: %s: %s" % (name, type(e).__name__, e))
        else:
            print("[ok] " + text)
    print("SELFTEST PASS" if not bad else "SELFTEST FAIL")
    return 1 if bad else 0


