class LReplayError(ValueError):
    """A bundle, a sample or a run that is not what lreplay replays; never guessed past."""


def check_bundle(bundle, name):
    """The seal, then optimise's tuning-only refusal, then the baseline system."""
    if not isinstance(bundle, dict) or bundle.get("schema") != BUNDLE_SCHEMA:
        raise LReplayError("bundle: %s is not a %s bundle" % (name, BUNDLE_SCHEMA))
    optimise.check_bundle(bundle, name)
    system = bundle["campaign"]["system"]
    if system in campaign.BASELINES:
        raise LReplayError("system: %s is a %s baseline; lreplay rebuilds configs "
                           "from the rules' records" % (name, system))


def load_bundle(path):
    """A tuning bundle read through the seal, or a named refusal."""
    if not os.path.isfile(path):
        raise LReplayError("no such bundle file: %s" % path)
    with open(path, "rb") as f:
        data = f.read()
    try:
        b = json.loads(gzip.decompress(data).decode("utf-8"))
    except (OSError, EOFError, ValueError, zlib.error) as e:
        raise LReplayError("bundle: %s does not decompress: %s" % (path, e))
    check_bundle(b, os.path.basename(path))
    return b


def _file_sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def rebuild_configs(bundle):
    """{(geometry_id, attempt): config} for every attempt row, from the bundle's
    own attempt-1 rule records and per-row config deltas - never rules.setup."""
    edits1 = {}
    for ln in bundle["records"]:
        rec = ln.get("record") or {}
        if ln.get("attempt") == 1 and rec.get("layer") == "rule":
            edits1.setdefault(ln["geometry_id"], []).extend(rec["edits"])
    by_geom = collections.OrderedDict()
    for r in bundle["attempts"]:
        by_geom.setdefault(r["geometry_id"], {})[r["attempt"]] = r
    out = {}
    for gid in sorted(by_geom):
        att = by_geom[gid]
        if sorted(att) != list(range(1, max(att) + 1)):
            raise LReplayError("attempts: %s holds %s, not 1..%d"
                               % (gid, sorted(att), max(att)))
        base = {"input": {"surfaces": [{"path": campaign.stl_rel(gid)}]},
                "output": {"case_dir": campaign.case_rel(gid), "name": gid}}
        cfg1 = optimise.apply_edits(base, edits1.get(gid, []))
        prev = None
        for a in sorted(att):
            row = att[a]
            parent = cfg1 if a == 1 else prev
            cfg = optimise.apply_edits(parent, row["config_delta"])
            got = schema.canonical_sha256(cfg)
            if got != row["config_sha"]:
                raise LReplayError("rebuild: %s attempt %d rebuilds to %s, the "
                                   "row says %s"
                                   % (gid, a, got[:12], row["config_sha"][:12]))
            prev = cfg
            out[(gid, a)] = cfg
    return out


def plane_geometries(bundle):
    """Gids whose attempt-1 rule record is an applied, non-empty R-PLANE edit."""
    out = set()
    for ln in bundle["records"]:
        rec = ln.get("record") or {}
        if (ln.get("attempt") == 1 and rec.get("rule_id") == "R-PLANE"
                and rec.get("verdict") == "apply" and rec.get("edits")):
            out.add(ln["geometry_id"])
    return out


def sample(bundle, n_other=N_OTHER):
    """The replay sample: every candidate R-PLANE row plus n_other rows drawn
    evenly over the (family, stratum) strata, picked by the sample salt."""
    ends = {g["geometry_id"]: g for g in bundle["geometries"]}
    cands = [r for r in bundle["attempts"]
             if r.get("content_sha256") is not None]
    planes = plane_geometries(bundle)
    plane_rows = [r for r in cands if r["geometry_id"] in planes]
    other = [r for r in cands if r["geometry_id"] not in planes]
    strata = {}
    for r in other:
        gid = r["geometry_id"]
        strata.setdefault((ends[gid]["family"], ends[gid]["stratum"]), []).append(r)
    keys = sorted(strata)
    S = len(keys)
    N = len(other)
    rest = n_other - S
    if rest < 0:
        raise LReplayError("sample: %d other rows over %d strata cannot give a "
                           "quota of one each within %d" % (N, S, n_other))
    q = {}
    frac = {}
    for k in keys:
        x = rest * len(strata[k]) / N
        q[k] = 1 + math.floor(x)
        frac[k] = x - math.floor(x)
    left = n_other - sum(q.values())
    for k in sorted(keys, key=lambda k: (-frac[k], k))[:max(left, 0)]:
        q[k] += 1
    for k in keys:
        if q[k] > len(strata[k]):
            raise LReplayError("sample: stratum %s/%s holds %d other rows, the "
                               "quota is %d" % (k[0], k[1], len(strata[k]), q[k]))
    picked = []
    for k in keys:
        rows = sorted(strata[k], key=lambda r: hashlib.sha256(
            ("%s|%s|%d" % (SAMPLE_SALT, r["geometry_id"], r["attempt"]))
            .encode("ascii")).hexdigest())
        picked.extend(rows[:q[k]])
    entries = []
    for r in plane_rows + picked:
        gid = r["geometry_id"]
        entries.append({"geometry_id": gid, "attempt": r["attempt"],
                        "family": ends[gid]["family"],
                        "stratum": ends[gid]["stratum"],
                        "plane": gid in planes,
                        "config_sha256": r["config_sha"],
                        "recorded_content_sha256": r["content_sha256"],
                        "recorded_seconds": r["outcome"]["seconds"]})
    entries.sort(key=lambda e: (e["geometry_id"], e["attempt"]))
    ids_text = "\n".join("%s:%d" % (e["geometry_id"], e["attempt"])
                         for e in entries)
    sha = hashlib.sha256(ids_text.encode("ascii")).hexdigest()
    return {"rows": entries, "n": len(entries), "n_plane": len(plane_rows),
            "n_plane_geometries": len({r["geometry_id"] for r in plane_rows}),
            "n_other": sum(q.values()), "n_other_pool": N,
            "n_candidates": len(cands), "n_rows_total": len(bundle["attempts"]),
            "n_strata": S,
            "quotas": {"%s/%s" % k: q[k] for k in keys}, "sha256": sha}


def plan_line(s):
    return ("lreplay plan: %d rows = %d R-PLANE rows on %d geometries + %d "
            "stratified of %d other rows (%d with a mesh of %d), sample sha256 %s"
            % (s["n"], s["n_plane"], s["n_plane_geometries"], s["n_other"],
               s["n_other_pool"], s["n_candidates"], s["n_rows_total"],
               s["sha256"]))


def fired_count(summary):
    """The sum of every FIRED_KEYS value over every layers patch, 0 without."""
    if not isinstance(summary, dict):
        return 0
    n = 0
    for st in (summary.get("stages") or []):
        if not isinstance(st, dict) or st.get("stage") != "layers":
            continue
        for p in (st.get("patches") or []):
            for key in FIRED_KEYS:
                n += int(p.get(key) or 0)
    return n


def verdict(recorded, replayed, exit_code, fired):
    if exit_code == 0 and replayed is not None and replayed == recorded:
        return "equal"
    if fired > 0:
        return "changed_fired"
    return "changed_unfired"


def report_ok(counts, expect_equal):
    for v in FAILING:
        if counts.get(v, 0) > 0:
            return False
    if expect_equal and counts.get("equal", 0) != sum(counts.values()):
        return False
    return True


def _mesh(c, gid, a, cfg, run_id):
    """The default mesh_fn, copied from campaign.run_attempt: write the config,
    one full run, the content sha, the summary read back, the polyMesh deleted."""
    campaign.write_config(c, gid, a, cfg)
    job = c.launch([c.binary, campaign.config_rel(gid, a), "-tag", "a%d" % a,
                    "-runId", run_id], cwd=c.dir, timeout_s=campaign.TIMEOUT_S,
                   kind="full", gid=gid, attempt=a, tag="a%d" % a)
    case = os.path.join(c.dir, "cases", "%s_a%d" % (gid, a))
    content = score.content_sha256(case) if job["exit_code"] == 0 else None
    spath = os.path.join(case, "%s_a%d_summary.json" % (gid, a))
    summary = None
    if os.path.isfile(spath):
        with open(spath, encoding="utf-8") as f:
            summary = json.load(f)
    shutil.rmtree(os.path.join(case, "constant", "polyMesh"), ignore_errors=True)
    shutil.rmtree(os.path.join(case, "mesh"), ignore_errors=True)
    return {"exit_code": job["exit_code"], "timed_out": job["timed_out"],
            "seconds": job["seconds"], "content_sha256": content,
            "summary": summary}


def _result(entry, v, replay, exit_code, timed_out, seconds, fired, stl_ok,
            fp_equal, reason):
    r = dict(entry)
    r.update({"verdict": v, "replay_content_sha256": replay,
              "exit_code": exit_code, "timed_out": timed_out, "seconds": seconds,
              "fired": fired, "stl_sha256_ok": stl_ok, "fp_equal": fp_equal,
              "reason": reason})
    return r


def _log_row(log, entry, res):
    if log:
        log("[lreplay] %s a%d %s %s replay %s recorded %s %.1f s"
            % (entry["geometry_id"], entry["attempt"],
               "plane" if entry["plane"] else "other", res["verdict"],
               (res["replay_content_sha256"] or "none")[:12],
               entry["recorded_content_sha256"][:12], res["seconds"] or 0.0))


def _task_rows(c, rows, cfgs, mrows, run_id, ends, observe_fn, mesh_fn, log):
    """One geometry: the surface regenerated and checked, then each attempt
    re-meshed and byte-compared; a fault fails its rows, never passes them."""
    gid = rows[0]["geometry_id"]
    judged = []
    try:
        obs = observe_fn(c, mrows[gid])
        if obs["terminal"] is not None:
            reason = "observe: %s: %s" % (obs["terminal"], obs.get("reason"))
            for e in rows:
                res = _result(e, "harness_error", None, None, None, None, None,
                              None, None, reason)
                judged.append(res)
                _log_row(log, e, res)
            return judged
        stl_sha = _file_sha256(os.path.join(c.dir, "stl", gid + ".stl"))
        want = ends[gid]["fingerprint"]["stl_sha256"]
        stl_ok = stl_sha == want
        fp_equal = (schema.canonical_sha256(obs["fingerprint"])
                    == schema.canonical_sha256(ends[gid]["fingerprint"]))
        if not stl_ok:
            reason = "stl sha %s, the row's surface is %s" % (stl_sha[:12],
                                                              want[:12])
            for e in rows:
                res = _result(e, "surface_mismatch", None, None, None, None,
                              None, False, fp_equal, reason)
                judged.append(res)
                _log_row(log, e, res)
            return judged
        for e in rows:
            m = mesh_fn(c, gid, e["attempt"], cfgs[(gid, e["attempt"])], run_id)
            fired = fired_count(m.get("summary"))
            v = verdict(e["recorded_content_sha256"], m.get("content_sha256"),
                        m.get("exit_code"), fired)
            res = _result(e, v, m.get("content_sha256"), m.get("exit_code"),
                          m.get("timed_out"), m.get("seconds"), fired, True,
                          fp_equal, None)
            judged.append(res)
            _log_row(log, e, res)
        return judged
    except Exception as e:  # noqa: BLE001 - a failing verdict, never a pass
        done = {(r["geometry_id"], r["attempt"]) for r in judged}
        reason = "%s: %s" % (type(e).__name__, e)
        for e2 in rows:
            if (e2["geometry_id"], e2["attempt"]) not in done:
                judged.append(_result(e2, "harness_error", None, None, None,
                                      None, None, None, None, reason))
        return judged


def run_rows(entries, bundle, cfgs, mrows, *, work, binary, streams,
             observe_fn=None, mesh_fn=None, log=None):
    """Every entry re-meshed through the campaign harness, one task per
    geometry, the results sorted by (geometry_id, attempt)."""
    os.makedirs(work, exist_ok=True)
    c = campaign.Campaign(work, campaign_id="lreplay", mode="rules",
                          system="rules", ablate=(),
                          split_mode=bundle["campaign"]["split_mode"],
                          binary=binary, streams=streams,
                          timeout_s=campaign.TIMEOUT_S,
                          probe_timeout_s=campaign.PROBE_TIMEOUT_S,
                          audit_mod=campaign.AUDIT_MOD, quiet=True)
    observe_fn = observe_fn or campaign.observe
    mesh_fn = mesh_fn or _mesh
    run_id = bundle["campaign"]["campaign_id"]
    ends = {g["geometry_id"]: g for g in bundle["geometries"]}
    by_gid = collections.OrderedDict()
    for e in entries:
        by_gid.setdefault(e["geometry_id"], []).append(e)
    for gid in by_gid:
        by_gid[gid].sort(key=lambda e: e["attempt"])
    out = []
    with ThreadPoolExecutor(max_workers=streams) as ex:
        futures = [ex.submit(_task_rows, c, rows, cfgs, mrows, run_id, ends,
                             observe_fn, mesh_fn, log)
                   for rows in by_gid.values()]
        for f in futures:
            out.extend(f.result())
    out.sort(key=lambda r: (r["geometry_id"], r["attempt"]))
    return out


def run(bundle_path, *, work, out, binary, streams=STREAMS_DEFAULT, ids=None,
        limit=None, expect_equal=False, log=print, observe_fn=None, mesh_fn=None):
    """The replay: refuse, load, rebuild, sample, select, run, report."""
    if not isinstance(streams, int) or not 1 <= streams <= MAX_STREAMS:
        raise LReplayError("streams: %r outside 1..%d (the house cap)"
                           % (streams, MAX_STREAMS))
    if not os.path.isfile(binary):
        raise LReplayError("no such binary: %s" % binary)
    if os.path.exists(work) and os.listdir(work):
        raise LReplayError("work: %s is not empty" % work)
    bundle = load_bundle(bundle_path)
    cfgs = rebuild_configs(bundle)
    s = sample(bundle)
    entries = s["rows"]
    if ids is not None:
        by_id = {"%s:%d" % (e["geometry_id"], e["attempt"]): e for e in entries}
        picked = []
        for gid_a in ids:
            e = by_id.get(gid_a)
            if e is None:
                raise LReplayError("id %s is not in the sample" % gid_a)
            picked.append(e)
        entries = picked
    if limit is not None:
        entries = entries[:limit]
    mrows = {r["geometry_id"]: r for r in campaign.load_manifest(
        "tuning", bundle["campaign"]["split_mode"],
        ids=sorted({e["geometry_id"] for e in entries}))}
    t0 = time.perf_counter()
    results = run_rows(entries, bundle, cfgs, mrows, work=work, binary=binary,
                       streams=streams, observe_fn=observe_fn, mesh_fn=mesh_fn,
                       log=log)
    counts = {v: sum(1 for r in results if r["verdict"] == v) for v in VERDICTS}
    ok = report_ok(counts, expect_equal)
    binary_sha = _file_sha256(binary)
    report = {"$comment": HEADER, "schema": LREPLAY_SCHEMA,
              "bundle": {"file": os.path.relpath(bundle_path, REPO)
                         .replace(os.sep, "/"),
                         "sha256": _file_sha256(bundle_path),
                         "campaign_id": bundle["campaign"]["campaign_id"],
                         "recorded_binary_sha256":
                             sorted({r["binary_sha"] for r in bundle["attempts"]})},
              "binary": {"file": os.path.basename(binary),
                         "sha256": binary_sha},
              "sample": {k: v for k, v in s.items() if k != "rows"},
              "selected": {"ids": ids is not None, "limit": limit,
                           "n": len(entries)},
              "expect_equal": expect_equal, "streams": streams,
              "rows": results, "counts": counts, "ok": ok,
              "wall_seconds": time.perf_counter() - t0}
    write_report(report, out)
    n_plane = sum(1 for r in results if r["plane"])
    log("lreplay: %d rows (%d R-PLANE), equal %d, changed_fired %d, "
        "changed_unfired %d, surface_mismatch %d, harness_error %d, "
        "binary %s -> %s"
        % (len(results), n_plane, counts["equal"], counts["changed_fired"],
           counts["changed_unfired"], counts["surface_mismatch"],
           counts["harness_error"], binary_sha[:12], "PASS" if ok else "FAIL"))
    return report


def write_report(report, path):
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(report, f, indent=1, sort_keys=True, ensure_ascii=False)
        f.write("\n")


class _ArgParser(argparse.ArgumentParser):
    """Usage errors exit 2, like campaign.py's."""

    def error(self, message):
        self.print_usage(sys.stderr)
        sys.stderr.write("lreplay: error: %s\n" % message)
        raise SystemExit(2)


def main(argv=None):
    ap = _ArgParser(description="recorded tuning rows re-meshed at their "
                                "recorded config, byte-compared")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--plan", action="store_true")
    ap.add_argument("--list", action="store_true", help="with --plan: the ids")
    ap.add_argument("--bundle", metavar="FILE", default=BUNDLE_DEFAULT)
    ap.add_argument("--run", action="store_true")
    ap.add_argument("--work", metavar="DIR")
    ap.add_argument("--out", metavar="FILE")
    ap.add_argument("--binary", metavar="EXE", default=campaign.BINARY_DEFAULT)
    ap.add_argument("--streams", type=int, default=STREAMS_DEFAULT)
    ap.add_argument("--ids", metavar="GID:A,...")
    ap.add_argument("--limit", type=int)
    ap.add_argument("--expect-equal", action="store_true")
    a = ap.parse_args(argv)
    chosen = [k for k, v in (("--selftest", a.selftest), ("--plan", a.plan),
                             ("--run", a.run)) if v]
    if len(chosen) != 1:
        ap.error("exactly one of --selftest, --plan, --run (got %s)"
                 % (", ".join(chosen) or "none"))
    if a.selftest:
        return selftest()
    if a.plan:
        s = sample(load_bundle(a.bundle))
        print(plan_line(s))
        if a.list:
            for e in s["rows"]:
                print("%s:%d %s %s/%s" % (e["geometry_id"], e["attempt"],
                                          "plane" if e["plane"] else "other",
                                          e["family"], e["stratum"]))
        return 0
    if not a.work or not a.out:
        ap.error("--run needs --work DIR and --out FILE")
    ids = None
    if a.ids is not None:
        ids = []
        for item in a.ids.split(","):
            gid, sep, num = item.partition(":")
            if not sep or not num:
                ap.error("--ids: %r is not GID:A" % item)
            try:
                ids.append("%s:%d" % (gid, int(num)))
            except ValueError:
                ap.error("--ids: %r is not GID:A" % item)
    try:
        rep = run(a.bundle, work=a.work, out=a.out, binary=a.binary,
                  streams=a.streams, ids=ids, limit=a.limit,
                  expect_equal=a.expect_equal)
    except (LReplayError, split.SplitSealed) as e:
        sys.stderr.write("lreplay: error: %s\n" % e)
        return 2
    return 0 if rep["ok"] else 1


