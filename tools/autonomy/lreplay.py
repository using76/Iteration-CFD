def _g5_scripted(H):
    s = sample(H["bundle"])
    seen = set()
    entries = []
    for e in s["rows"]:
        if e["geometry_id"] not in seen:
            seen.add(e["geometry_id"])
            entries.append(copy.deepcopy(e))
        if len(entries) == 5:
            break
    want = hashlib.sha256(b"solid lreplay-selftest\n").hexdigest()
    b5 = copy.deepcopy(H["bundle"])
    ends = {g["geometry_id"]: g for g in b5["geometries"]}
    for e in entries:
        ends[e["geometry_id"]]["fingerprint"]["stl_sha256"] = want
    gid1, gid2 = entries[0]["geometry_id"], entries[1]["geometry_id"]
    gid3, gid4 = entries[2]["geometry_id"], entries[3]["geometry_id"]
    gid5 = entries[4]["geometry_id"]

    def obs(c, mrow):
        gid = mrow["geometry_id"]
        os.makedirs(os.path.join(c.dir, "stl"), exist_ok=True)
        if gid == gid5:
            return {"terminal": "HARNESS-ERROR", "reason": "scripted"}
        body = b"solid other\n" if gid == gid4 else b"solid lreplay-selftest\n"
        with open(os.path.join(c.dir, "stl", gid + ".stl"), "wb") as f:
            f.write(body)
        return {"terminal": None, "fingerprint": ends[gid]["fingerprint"]}

    def mesh(c, gid, a, cfg, run_id):
        rec = next(e["recorded_content_sha256"] for e in entries
                   if e["geometry_id"] == gid)
        if gid == gid2:
            summary = {"stages": [{"stage": "layers",
                                   "patches": [{"n_reseated_points": 4}]}]}
            body = "0" * 64
        else:
            summary, body = None, (rec if gid == gid1 else "1" * 64)
        return {"exit_code": 0, "timed_out": False, "seconds": 1.0,
                "content_sha256": body, "summary": summary}
    cfgs = rebuild_configs(H["bundle"])
    mrows = {e["geometry_id"]: {"geometry_id": e["geometry_id"]}
             for e in entries}
    with tempfile.TemporaryDirectory() as tmp:
        results = run_rows(entries, b5, cfgs, mrows,
                           work=os.path.join(tmp, "w"), binary=sys.executable,
                           streams=2, observe_fn=obs, mesh_fn=mesh)
        vs = [r["verdict"] for r in results]
        assert vs == ["equal", "changed_fired", "changed_unfired",
                      "surface_mismatch", "harness_error"], vs
        counts = {v: sum(1 for r in results if r["verdict"] == v)
                  for v in VERDICTS}
        assert sorted(counts.values()) == [1] * 5, counts
        assert not report_ok(counts, False), counts
        two = run_rows(entries[:2], b5, cfgs, mrows,
                       work=os.path.join(tmp, "w2"), binary=sys.executable,
                       streams=2, observe_fn=obs, mesh_fn=mesh)
        c2 = {v: sum(1 for r in two if r["verdict"] == v) for v in VERDICTS}
        assert report_ok(c2, False), c2
        assert not report_ok(c2, True), c2
        small = {"$comment": HEADER, "schema": LREPLAY_SCHEMA, "ok": True}
        rp = os.path.join(tmp, "r", "x.json")
        write_report(small, rp)
        with open(rp, encoding="utf-8") as f:
            assert json.load(f) == small
    return ("scripted run: five scripted geometries give equal 1, "
            "changed_fired 1, changed_unfired 1, surface_mismatch 1 and "
            "harness_error 1, and the run is not ok; the report round-trips")


