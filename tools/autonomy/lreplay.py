"""
lreplay.py - recorded tuning rows re-meshed at their recorded config, byte-compared.

The sample is every row of an R-PLANE geometry plus 60 rows stratified by family
and stratum, all with a recorded content sha; each config is rebuilt from the
bundle's own records and deltas and checked against the row's config sha; the
surface is regenerated by campaign.observe and checked against the row's stl
sha; the mesh is compared by score.content_sha256; a changed row is
`changed_fired` only when the layers report carries `n_reseated_points` > 0,
else `changed_unfired`, which fails the run.

The seal holds (a bundle that is not a tuning campaign is refused); the test
split is spent and is not read.

    python tools/autonomy/lreplay.py --plan [--list] [--bundle FILE]
    python tools/autonomy/lreplay.py --run --work DIR --out FILE [--binary EXE] [--streams N] [--ids GID:A,...] [--limit N] [--expect-equal]
    python tools/autonomy/lreplay.py --selftest
"""
