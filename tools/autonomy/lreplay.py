def _g2_rebuild(H):
    b = H["bundle"]
    cfgs = rebuild_configs(b)
    assert len(cfgs) == 805, len(cfgs)
    for r in b["attempts"]:
        got = schema.canonical_sha256(cfgs[(r["geometry_id"], r["attempt"])])
        assert got == r["config_sha"], (r["geometry_id"], r["attempt"])
    import rules
    old = rules.setup

    def _no_setup(*_a, **_k):
        raise AssertionError("rules.setup called")

    rules.setup = _no_setup
    try:
        cfgs2 = rebuild_configs(b)
    finally:
        rules.setup = old
    assert len(cfgs2) == 805, len(cfgs2)
    b3 = copy.deepcopy(b)
    for r in b3["attempts"]:
        if r.get("config_delta"):
            r["config_delta"][0]["to"] = "lreplay-selftest"
            break
    try:
        rebuild_configs(b3)
    except LReplayError as e:
        assert "rebuilds to" in str(e), str(e)
    else:
        raise AssertionError("a changed delta was not refused")
    b4 = copy.deepcopy(b)
    for ln in b4["records"]:
        rec = ln.get("record") or {}
        if ln.get("attempt") == 1 and rec.get("layer") == "rule" \
                and rec.get("edits"):
            rec["edits"] = []
            break
    try:
        rebuild_configs(b4)
    except LReplayError as e:
        assert "rebuilds to" in str(e), str(e)
    else:
        raise AssertionError("a dropped rule edit was not refused")
    b5 = copy.deepcopy(b)
    for r in list(b5["attempts"]):
        gid = r["geometry_id"]
        has3 = any(x["geometry_id"] == gid and x["attempt"] == 3
                   for x in b5["attempts"])
