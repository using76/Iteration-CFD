//! SPEC-LIT §120's catalogue as the JSON the studio reads (docs/17 BC-22).
//!
//! [`emit_bc_catalogue`] writes [`crate::field::IMPLEMENTED_BC_NAMES`] and
//! every row of [`super::catalogue::CATALOGUE`] as one JSON document;
//! `docs/schema/bc-catalogue-1.json` is that document and
//! `gui/shared/src/bcCatalogue.data.ts` is the same text as a TypeScript
//! constant. Neither file is edited by hand: when the catalogue gains a
//! name, [`the_shipped_bc_catalogue_is_the_generated_one`] rewrites both
//! and fails once, naming them, so the change is committed with the name.
//! The gui's `registry/sync.test.ts` holds its copy to the JSON and to the
//! two Rust sources it comes from.
//!
//! The catalogue lists no per-name entry keys, so neither does this
//! document; a JSONC case's per-field conditions and their required members
//! are `docs/schema/case-1.json`'s `ScalarBc`, `VectorBc` and `TurbBc`.

use serde_json::{json, Map, Value};

use super::catalogue::{Status, CATALOGUE};
use super::IMPLEMENTED_BC_NAMES;

/// The shipped JSON, relative to `CARGO_MANIFEST_DIR`.
const JSON_PATH: &str = "../docs/schema/bc-catalogue-1.json";
/// The shipped TypeScript copy, relative to `CARGO_MANIFEST_DIR`.
const TS_PATH: &str = "../gui/shared/src/bcCatalogue.data.ts";

/// The status word of one row, as the JSON spells it.
fn status_word(s: Status) -> &'static str {
    match s {
        Status::Implemented => "implemented",
        Status::Alias { .. } => "alias",
        Status::Planned { .. } => "planned",
        Status::Owned { .. } => "owned",
        Status::Refused { .. } => "refused",
    }
}

/// The catalogue document: pretty-printed JSON with a trailing newline.
pub(crate) fn emit_bc_catalogue() -> String {
    let words = ["implemented", "alias", "planned", "owned", "refused"];
    let mut counts = Map::new();
    for w in words {
        let n = CATALOGUE.iter().filter(|e| status_word(e.status) == w).count();
        counts.insert(w.to_string(), json!(n));
    }
    let entries: Vec<Value> = CATALOGUE
        .iter()
        .map(|e| {
            let mut row = Map::new();
            row.insert("family".into(), json!(e.family));
            row.insert("name".into(), json!(e.name));
            row.insert("status".into(), json!(status_word(e.status)));
            match e.status {
                Status::Implemented => {}
                Status::Alias { to } => {
                    row.insert("to".into(), json!(to));
                }
                Status::Planned { unit } | Status::Owned { unit } => {
                    row.insert("unit".into(), json!(unit));
                }
                Status::Refused { key } => {
                    row.insert("reason".into(), json!(key));
                }
            }
            row.insert("field".into(), json!(e.field));
            row.insert("extendedBy".into(), json!(e.extended_by));
            row.insert("probes".into(), json!(e.probes));
            Value::Object(row)
        })
        .collect();
    let doc = json!({
        "$comment": "Generated from IMPLEMENTED_BC_NAMES (rust/src/field.rs) and CATALOGUE \
                     (rust/src/field/catalogue.rs) by field::catalogue_json (docs/17 BC-22, \
                     SPEC-LIT 120). Do not edit: a run of \
                     field::catalogue_json::the_shipped_bc_catalogue_is_the_generated_one rewrites it.",
        "version": 1,
        "counts": Value::Object(counts),
        "implemented": IMPLEMENTED_BC_NAMES,
        "entries": entries,
    });
    let mut text = serde_json::to_string_pretty(&doc).expect("the catalogue serialises");
    text.push('\n');
    text
}

/// The TypeScript copy of `json`: the same text, typed by `bcCatalogue.ts`.
pub(crate) fn emit_bc_catalogue_ts(json: &str) -> String {
    format!(
        "// meteor-cfd - Copyright (c) 2026 주식회사 이터레이션즈 (Iterations Co., Ltd.). See LICENSE at the repository root.\n\
         // No GPL-licensed source was consulted.\n\
         // GENERATED by rust/src/field/catalogue_json.rs (docs/17 BC-22): docs/schema/bc-catalogue-1.json\n\
         // as a constant. Do not edit; registry/sync.test.ts holds it to the JSON and the Rust sources.\n\
         import type {{ BcCatalogue }} from './bcCatalogue'\n\
         \n\
         export const BC_CATALOGUE_DATA: BcCatalogue = {}",
        json
    )
}

/// Line endings normalised: git may check a file out with CRLF.
fn norm(s: &str) -> String {
    s.replace("\r\n", "\n")
}

/// SPEC-LIT §120: the document carries every catalogue row, in order, and
/// exactly the implemented list.
#[test]
fn the_json_carries_every_catalogue_row() {
    let v: Value = serde_json::from_str(&emit_bc_catalogue()).expect("valid JSON");
    let entries = v["entries"].as_array().expect("entries");
    assert_eq!(entries.len(), CATALOGUE.len());
    for (row, e) in entries.iter().zip(CATALOGUE) {
        assert_eq!(row["name"], e.name);
        assert_eq!(row["family"], e.family);
        assert_eq!(row["status"], status_word(e.status));
        assert_eq!(row["field"], e.field);
    }
    let implemented: Vec<&str> =
        v["implemented"].as_array().unwrap().iter().map(|x| x.as_str().unwrap()).collect();
    assert_eq!(implemented, IMPLEMENTED_BC_NAMES);

    // The counts are the rows' statuses and sum to the catalogue.
    let c = &v["counts"];
    let total: u64 = ["implemented", "alias", "planned", "owned", "refused"]
        .iter()
        .map(|w| c[*w].as_u64().unwrap())
        .sum();
    assert_eq!(total as usize, CATALOGUE.len());
    assert_eq!(c["implemented"].as_u64().unwrap() as usize, IMPLEMENTED_BC_NAMES.len());
    println!(
        "bc catalogue counts [{}, {}, {}, {}, {}] of {}",
        c["implemented"], c["alias"], c["planned"], c["owned"], c["refused"], total
    );

    // Spot rows.
    assert_eq!(entries[0]["name"], "fixedValue");
    assert_eq!(entries[0]["status"], "implemented");
    assert_eq!(entries[0]["family"], "basic");
    assert_eq!(entries[0]["field"], "psi");
    assert!(entries[0].get("to").is_none() && entries[0].get("unit").is_none());
    let spalding = entries.iter().find(|r| r["name"] == "nutUSpaldingWallFunction").unwrap();
    assert_eq!(spalding["status"], "alias");
    assert_eq!(spalding["to"], "nutUWallFunction");
    for r in entries.iter().filter(|r| r["status"] == "refused") {
        assert!(!r["reason"].as_str().unwrap().is_empty(), "{r}");
    }
    for r in entries.iter().filter(|r| r["status"] == "planned" || r["status"] == "owned") {
        assert!(!r["unit"].as_str().unwrap().is_empty(), "{r}");
    }
}

/// The shipped JSON and its TypeScript copy ARE the generated text. A stale
/// pair is rewritten and the test fails once, naming both, so the
/// regenerated files go into the commit that changed the catalogue.
#[test]
fn the_shipped_bc_catalogue_is_the_generated_one() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let json = emit_bc_catalogue();
    let ts = emit_bc_catalogue_ts(&json);
    let mut stale = Vec::new();
    for (rel, want) in [(JSON_PATH, &json), (TS_PATH, &ts)] {
        let path = root.join(rel);
        let shipped = std::fs::read_to_string(&path).unwrap_or_default();
        if norm(&shipped) != norm(want) {
            std::fs::write(&path, want).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
            stale.push(rel);
        }
    }
    assert!(
        stale.is_empty(),
        "{stale:?} had drifted from the catalogue and were regenerated; commit them"
    );
}
