export type ExtraKey = keyof typeof EXTRA.ko
export type UiKey = StringKey | ExtraKey

const SHARED_KEYS = new Set<string>(Object.keys(STRING_TABLES.ko))

export function tx(locale: Locale, key: UiKey, vars?: Record<string, string | number>): string {
  if (SHARED_KEYS.has(key)) return sharedT(locale, key as StringKey, vars)
  const table = EXTRA[locale] as Record<string, string>
  let s = table[key] ?? (EXTRA.en as Record<string, string>)[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
  return s
}

