export type StringKey = keyof typeof STRINGS.ko

export function t(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  const table = STRINGS[locale] as Record<string, string>
  let s = table[key] ?? (STRINGS.en as Record<string, string>)[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
  return s
}

